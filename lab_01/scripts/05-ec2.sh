#!/usr/bin/env bash
# Two web servers (EC2, Amazon Linux 2023), one per AZ. Each boots with
# wordpress/bootstrap.sh as user-data, which mounts EFS, installs Apache + PHP,
# downloads WordPress, points it at RDS and starts Apache.
. "$(dirname "$0")/lib/common.sh"
load_state   # VPC/subnets + WEB_SG, EFS_ID, DB_ENDPOINT from the earlier scripts
ensure_secrets
DB_HOST=$DB_ENDPOINT

# 1. Latest Amazon Linux 2023 AMI for the instance type's CPU architecture.
ARCH=$(aws ec2 describe-instance-types --instance-types "$INSTANCE_TYPE" \
  --query 'InstanceTypes[0].ProcessorInfo.SupportedArchitectures[0]' --output text)
AMI_ID=$(aws ssm get-parameter \
  --name "/aws/service/ami-amazon-linux-latest/al2023-ami-kernel-default-$ARCH" \
  --query Parameter.Value --output text)
ok "AMI = $AMI_ID ($ARCH)"

# 2. User-data = configuration variables + wordpress/bootstrap.sh.
USER_DATA="$STATE_DIR/user-data.sh"
(
  umask 077
  {
    echo '#!/bin/bash'
    echo '# Generated by scripts/05-ec2.sh -- do not edit'
    for v in EFS_ID DB_HOST DB_NAME DB_USER DB_PASSWORD \
             WP_AUTH_KEY WP_SECURE_AUTH_KEY WP_LOGGED_IN_KEY WP_NONCE_KEY \
             WP_AUTH_SALT WP_SECURE_AUTH_SALT WP_LOGGED_IN_SALT WP_NONCE_SALT; do
      printf '%s=%q\n' "$v" "${!v}"
    done
    sed '1{/^#!/d;}' "$LAB_DIR/wordpress/bootstrap.sh"
  } > "$USER_DATA"
)

# 3. Web server 1 in subnet 1 (AZ 1).
WEB_1_ID=$(aws ec2 run-instances \
  --image-id "$AMI_ID" --instance-type "$INSTANCE_TYPE" --key-name "$KEY_NAME" \
  --subnet-id "$SUBNET_1" --security-group-ids "$WEB_SG" --associate-public-ip-address \
  --metadata-options HttpTokens=required,HttpEndpoint=enabled \
  --user-data "file://$USER_DATA" \
  --tag-specifications "ResourceType=instance,Tags=[{Key=Name,Value=$PROJECT-web-1},{Key=Project,Value=$PROJECT}]" \
  --query 'Instances[0].InstanceId' --output text)
ok "$PROJECT-web-1 = $WEB_1_ID ($AZ_1)"

# 4. Web server 2 in subnet 2 (AZ 2).
WEB_2_ID=$(aws ec2 run-instances \
  --image-id "$AMI_ID" --instance-type "$INSTANCE_TYPE" --key-name "$KEY_NAME" \
  --subnet-id "$SUBNET_2" --security-group-ids "$WEB_SG" --associate-public-ip-address \
  --metadata-options HttpTokens=required,HttpEndpoint=enabled \
  --user-data "file://$USER_DATA" \
  --tag-specifications "ResourceType=instance,Tags=[{Key=Name,Value=$PROJECT-web-2},{Key=Project,Value=$PROJECT}]" \
  --query 'Instances[0].InstanceId' --output text)
ok "$PROJECT-web-2 = $WEB_2_ID ($AZ_2)"

save WEB_1_ID WEB_2_ID

log "Waiting for instances to be running..."
aws ec2 wait instance-running --instance-ids "$WEB_1_ID" "$WEB_2_ID"

WEB_1_IP=$(aws ec2 describe-instances --instance-ids "$WEB_1_ID" \
  --query 'Reservations[0].Instances[0].PublicIpAddress' --output text)
WEB_2_IP=$(aws ec2 describe-instances --instance-ids "$WEB_2_ID" \
  --query 'Reservations[0].Instances[0].PublicIpAddress' --output text)
ok "web-1 running, public IP $WEB_1_IP"
ok "web-2 running, public IP $WEB_2_IP"
log "WordPress bootstrap runs in the background on each VM (~3-5 min). Logs: make logs N=1"
